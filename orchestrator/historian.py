"""HISTORIAN — persistent, structured design state + human-readable document.

The seed makes the HISTORIAN a role, but its job (track proposals, attacks,
verdicts, tradeoffs; prevent re-litigating settled questions; emit the running
design document) is bookkeeping, so we implement it as deterministic code rather
than an LLM. Determinism here is a feature: the audit trail of WHY a decision is
in the document must not itself be a hallucination.

state.json is the machine-readable source of truth. DESIGN.md is rendered from
it and is disposable. The 'incompatibilities' list is the eventual payload
(Section 8): the map of which target properties cannot coexist, proven by
survived challenge rather than asserted.
"""
from __future__ import annotations

import datetime
import json
from pathlib import Path

STATE_VERSION = 1


def _now() -> str:
    return datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")


class Historian:
    def __init__(self, design_dir: Path):
        self.dir = Path(design_dir)
        self.dir.mkdir(parents=True, exist_ok=True)
        self.state_path = self.dir / "state.json"
        self.doc_path = self.dir / "DESIGN.md"
        self.state = self._load()

    def _load(self) -> dict:
        if self.state_path.exists():
            return json.loads(self.state_path.read_text())
        return {
            "version": STATE_VERSION,
            "created": _now(),
            "rounds": [],            # every round, survived or failed
            "settled": [],           # decisions that survived (the design)
            "incompatibilities": [], # the payload: forced property conflicts
            "blind_spot_flags": [],  # coldness alarms
            "total_cost_usd": 0.0,
        }

    # --- queries ---------------------------------------------------------
    def settled(self) -> list[dict]:
        return self.state["settled"]

    def is_settled(self, question: str) -> bool:
        return any(d["question"] == question for d in self.state["settled"])

    def revisions_for(self, question: str) -> int:
        return sum(
            1 for r in self.state["rounds"]
            if r["question"] == question and r["outcome"] == "FAILED"
        )

    # --- mutations -------------------------------------------------------
    def record_round(self, round_rec: dict) -> None:
        round_rec.setdefault("timestamp", _now())
        self.state["rounds"].append(round_rec)
        self.state["total_cost_usd"] = round(
            self.state["total_cost_usd"] + round_rec.get("cost_usd", 0.0), 4
        )

    def settle(self, decision: dict) -> None:
        decision.setdefault("timestamp", _now())
        # replace any prior settled entry for the same question (re-opened)
        self.state["settled"] = [
            d for d in self.state["settled"] if d["question"] != decision["question"]
        ]
        self.state["settled"].append(decision)

    def record_incompatibility(self, incomp: dict) -> None:
        incomp.setdefault("timestamp", _now())
        self.state["incompatibilities"].append(incomp)

    def flag_blind_spot(self, note: str, round_no: int) -> None:
        self.state["blind_spot_flags"].append(
            {"round": round_no, "note": note, "timestamp": _now()}
        )

    def save(self) -> None:
        self.state_path.write_text(json.dumps(self.state, indent=2))
        self.doc_path.write_text(self._render_doc())

    # --- rendering -------------------------------------------------------
    def _render_doc(self) -> str:
        s = self.state
        out: list[str] = []
        out.append("# Adversarially-Survived Language Design")
        out.append("")
        out.append(f"*Generated by the orchestrator. {len(s['settled'])} decision(s) "
                   f"settled across {len(s['rounds'])} round(s). "
                   f"Notional cost ${s['total_cost_usd']:.2f}.*")
        out.append("")
        out.append("This document is rendered from `state.json`; edit the process, "
                   "not this file.")
        out.append("")

        out.append("## The Payload — Forced Incompatibilities")
        out.append("")
        out.append("*Section 8 of the seed: the combinations of target properties "
                   "proven incompatible by survived challenge, not asserted.*")
        out.append("")
        if s["incompatibilities"]:
            for i in s["incompatibilities"]:
                src = i.get("source", "reconcile")
                origin = ("within failed question" if src == "revision-exhaustion"
                          else "between settled decisions")
                out.append(f"- **[{i.get('severity','?').upper()}] "
                           f"{i['between'][0]} ✕ {i['between'][1]}**  "
                           f"<sub>({origin})</sub>")
                out.append(f"  - property at risk: *{i.get('property_at_risk','?')}*")
                if i.get("from_question"):
                    out.append(f"  - surfaced by: {i['from_question']}")
                out.append(f"  - {i.get('description','')}")
        else:
            out.append("*None recorded yet. (Expected until ≥2 decisions are "
                       "settled — the first recorded incompatibility is the signal "
                       "the process is doing real work.)*")
        out.append("")

        out.append("## Settled Decisions")
        out.append("")
        if not s["settled"]:
            out.append("*None yet.*")
        for d in s["settled"]:
            out.append(f"### {d['question']}")
            out.append(f"*Settled round {d.get('round','?')} "
                       f"(after {d.get('revisions',0)} revision(s)). "
                       f"Verdict: {d.get('verdict','SURVIVED')}.*")
            out.append("")
            out.append(f"**Commits to:** {d.get('headline','—')}")
            out.append("")
            if d.get("tradeoffs"):
                out.append("**Tradeoffs carried:**")
                for t in d["tradeoffs"]:
                    out.append(f"- {t}")
                out.append("")
            out.append("<details><summary>Full proposal text</summary>")
            out.append("")
            out.append(d.get("proposal_text", "").strip())
            out.append("")
            out.append("</details>")
            out.append("")

        if s["blind_spot_flags"]:
            out.append("## ⚠️ Coldness / Blind-Spot Flags")
            out.append("")
            out.append("*Rounds where attackers found nothing — suspicious per the "
                       "seed's correlated-blind-spot warning.*")
            out.append("")
            for f in s["blind_spot_flags"]:
                out.append(f"- Round {f['round']}: {f['note']}")
            out.append("")

        out.append("## Round Log")
        out.append("")
        for r in s["rounds"]:
            mark = {"SURVIVED": "✅", "FAILED": "❌", "TRADEOFF": "⚖️"}.get(
                r["outcome"], "•")
            out.append(f"- {mark} **R{r['round']}** [{r['question']}] "
                       f"rev{r.get('revision',0)} → {r['outcome']} "
                       f"(${r.get('cost_usd',0):.2f})")
        out.append("")
        return "\n".join(out)
